-- Borra la base de datos Clinica si ya existe y la crea desde cero
IF DB_ID('Clinica') IS NOT NULL
BEGIN
    ALTER DATABASE Clinica SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE Clinica;
END
GO

CREATE DATABASE Clinica;
GO

USE Clinica;
GO

-- =========================
-- TABLA PACIENTES
-- =========================
CREATE TABLE Pacientes (
    Id_Paciente INT IDENTITY(1,1) PRIMARY KEY,
    Nombres NVARCHAR(100) NOT NULL,
    Apellidos NVARCHAR(100) NOT NULL,
    Sexo NVARCHAR(10) NOT NULL CHECK (Sexo IN (N'MASCULINO', N'FEMENINO')),
    Fecha_Nacimiento DATE NOT NULL,
    Domicilio NVARCHAR(150),
    Tipo_Sangre NVARCHAR(20),
    Alergias NVARCHAR(100),
    Telefono NVARCHAR(15),
    Nombre_Contacto_Emergencia NVARCHAR(100),
    Telefono_Contacto_Emergencia NVARCHAR(15)
);
GO

-- =========================
-- TABLA MEDICOS
-- =========================
CREATE TABLE Medicos (
    Id_Med INT IDENTITY(1,1) PRIMARY KEY,
    Nombre NVARCHAR(100) NOT NULL,
    Apellido NVARCHAR(100) NOT NULL,
    Especialidad NVARCHAR(100),
    Tel_Med NVARCHAR(15),
    Fecha_Ingreso DATE
);
GO

